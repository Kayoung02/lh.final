import pandas as pd
import streamlit as st


def render_renewal_map() -> None:
    st.subheader("정비사업 분석 확장 방향")
    st.caption("현재 대시보드의 단기 구현 범위는 1·2번 탭입니다. 이 탭은 향후 정비사업 데이터를 확장할 때의 분석 설계를 제시합니다.")

    st.markdown("#### 확장 목표")
    goal1, goal2, goal3 = st.columns(3)
    goal1.metric("정비사업 원장", "사업·단계·공급량", "자치구·사업유형·추진단계")
    goal2.metric("시공사 선정 근거", "검증 가능한 기록", "DART · 조합 · 건설사 공식자료")
    goal3.metric("공간 분석", "기존 단지와 연결", "인접 시공 이력·브랜드 분포")

    st.markdown("#### 구축 순서")
    roadmap = pd.DataFrame(
        [
            ["1단계 · 원장 정비", "서울시 정비사업 추진현황", "사업명·자치구·주소·사업방식·추진단계·공급세대수 표준화"],
            ["2단계 · 선정 근거 축적", "DART·조합 공고·건설사 보도자료", "시공사·선정일·브랜드·원문 URL·검증상태 기록"],
            ["3단계 · 공간 연결", "의제처리구역·기존 공동주택", "사업구역과 인근 시공사의 기존 공급 이력을 비교"],
            ["4단계 · 해석", "시공사·브랜드·사업단계", "확정·입찰·우선협상 상태를 구분한 현황 탐색"],
        ],
        columns=["단계", "필요 데이터", "대시보드에서 보는 내용"],
    )
    st.dataframe(roadmap, hide_index=True, use_container_width=True)

    st.markdown("#### 향후 지도에서 제공할 정보")
    future_map = pd.DataFrame(
        [
            ["정비사업 구역", "사업명, 자치구, 사업방식, 추진단계, 계획 공급세대수"],
            ["시공사 선정 완료", "시공사, 브랜드, 선정일, 계약·선정 근거 원문 링크"],
            ["입찰·우선협상 단계", "확정 정보와 분리해 ‘검토 중’으로 표시"],
            ["인근 공동주택 이력", "반경 내 기존 시공사·브랜드 단지의 분포와 보정 점유율"],
        ],
        columns=["지도 레이어", "표시 정보"],
    )
    st.dataframe(future_map, hide_index=True, use_container_width=True)

    st.markdown("#### 검증 원칙")
    st.markdown(
        """
- **확정 표기**: 시공사 선정·계약 체결을 확인할 수 있는 DART 공시, 조합 공식자료, 건설사 공식자료가 있는 경우
- **검토 중 표기**: 입찰 공고, 우선협상대상자, 언론 단독 보도 등 최종 선정이 아닌 경우
- **브랜드 표기**: 시공사 선정과 별개로 브랜드가 공식적으로 확인된 경우에만 표시
- **해석 유의**: 인근 시공 이력은 현황 비교를 위한 정보이며, 향후 수주나 브랜드 전략을 예측하는 근거로 단정하지 않음
"""
    )

    st.info("정비사업 시공사 선정 근거가 충분히 축적된 뒤, 이 탭을 지도·근거 링크·인접 단지 비교 화면으로 확장합니다.")
